"""Build the game's multilingual catalogs from the review sheet (multilingual work, docs/다국어-설계-20261113.md).

  python tools/i18n_build.py [--csv i18n/review.csv] [--out Augustus/i18n]

review.csv (UTF-8, Excel-friendly) has one row per Korean text: ko, en, ru, de, es, fr. For every language with at
least one translation, Augustus/i18n/<code>.tsv is written: "korean<TAB>translation" per line, \\n \\t \\\\ escaped,
which src/core/mp_i18n.c reads (the game finds the folder through AUGUSTUS_I18N_DIR, set by network_play.py).
Empty cells are left out, so the game shows the Korean text there.

Slots: a Korean text with values (%d, %s ... or {0} {1} ...) is a template. The translation writes {0} {1} ... for the
1st, 2nd ... value, in any order. Rows whose translation names a slot the Korean text does not have, or drops one,
are reported and left out (a wrong number in a message is worse than Korean)."""
import argparse,csv,re,sys
from pathlib import Path

LANGS=['en','ru','de','es','fr']
PRINTF=re.compile(r'%[-+ #0]*\d*(?:\.\d+)?(?:hh|h|ll|l|z)?[diuxXsScfgeEp]')
BRACE=re.compile(r'\{(\d+)\}')
# a translation like '45 % der' is ordinary text: no space flag when looking for stray printf specs
STRICT_PRINTF=re.compile(r'%[-+#0]*\d*(?:\.\d+)?(?:hh|h|ll|l|z)?[diuxXsScfgeEp]')

def slots(korean):
    """Number of values in a Korean text (printf specs and {n} together, as mp_i18n.c counts them)."""
    t=korean.replace('%%','')
    printf=len(PRINTF.findall(t))
    brace=[int(n) for n in BRACE.findall(t)]
    return printf+len(brace),set(range(printf))|set(brace)

def escape(text):
    return text.replace('\\','\\\\').replace('\t','\\t').replace('\r\n','\n').replace('\n','\\n')

def check(korean,translation):
    count,names=slots(korean)
    used={int(n) for n in BRACE.findall(translation)}
    if used-names:return 'unknown slot '+','.join('{%d}'%n for n in sorted(used-names))
    if count and used!=names:return 'missing slot '+','.join('{%d}'%n for n in sorted(names-used))
    if not count and STRICT_PRINTF.search(translation.replace('%%','')):return 'printf in a plain text'
    return None

HANGUL=re.compile('[\uac00-\ud7a3]')

def pairs(korean,translation):
    """The game translates line by line (src/core/mp_i18n.c), so a text with line breaks becomes one pair per line.
    printf slots are numbered per line in the game; the sheet numbers them over the whole text, so they are
    renumbered here. Lines without Korean (only values or symbols) need no entry."""
    ko_lines=korean.split('\n');tr_lines=translation.split('\n')
    if len(ko_lines)==1:return [(korean,translation)]
    if len(ko_lines)!=len(tr_lines):raise ValueError('line count %d/%d'%(len(ko_lines),len(tr_lines)))
    out=[];before=0
    for k,t in zip(ko_lines,tr_lines):
        n=len(PRINTF.findall(k.replace('%%','')))
        if n and before:t=BRACE.sub(lambda m:'{%d}'%(int(m.group(1))-before) if before<=int(m.group(1))<before+n else m.group(0),t)
        if HANGUL.search(k) and t:out.append((k,t))
        before+=n
    return out

def build(csv_path,out):
    rows=list(csv.DictReader(open(csv_path,encoding='utf-8-sig',newline='')))
    out.mkdir(parents=True,exist_ok=True);report={}
    for lang in LANGS:
        lines=[];problems=[];seen=set()
        for r in rows:
            ko=r.get('ko') or '';tr=(r.get(lang) or '').replace('\r\n','\n') if '\r\n' not in ko else (r.get(lang) or '')
            if not ko or not tr.strip():continue
            why=check(ko,tr)
            if why:problems.append((r.get('id',''),why,ko[:40]));continue
            try:parts=pairs(ko,tr)
            except ValueError as error:problems.append((r.get('id',''),str(error),ko[:40]));continue
            for k,t in parts:
                if k not in seen:seen.add(k);lines.append(escape(k)+'\t'+escape(t))
        path=out/f'{lang}.tsv'
        if lines:
            path.write_text('# generated by tools/i18n_build.py from review.csv - edit review.csv, not this file\n'+'\n'.join(lines)+'\n',encoding='utf-8')
        elif path.exists():path.unlink()
        report[lang]=(len(lines),problems)
    return report,len(rows)

def main(argv):
    root=Path(__file__).resolve().parents[1]
    ap=argparse.ArgumentParser();ap.add_argument('--csv',type=Path,default=root/'i18n/review.csv');ap.add_argument('--out',type=Path,default=root/'Augustus/i18n')
    a=ap.parse_args(argv);report,total=build(a.csv,a.out)
    for lang,(n,problems) in report.items():
        print(f'{lang}: {n}/{total} translated'+(f', {len(problems)} left out' if problems else ''))
        for p in problems[:20]:print('   ',*p)
    return 1 if any(p for _,p in report.values()) else 0

if __name__=='__main__':sys.exit(main(sys.argv[1:]))
